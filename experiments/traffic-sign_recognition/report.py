"""Collect the grid's runs into a comparison table, curated artifacts and a manifest.

Reads what training already wrote — no re-running, no GPU:

* ``run_meta.json``  headline metrics from the *best* checkpoint, wall time, sha256
* ``results.csv``    per-epoch curves, and ``lr/pg0`` — the learning rate
                     ``optimizer="auto"`` actually chose (ultralytics writes these
                     columns at ``engine/trainer.py:530``)
* ``args.yaml``      the resolved training arguments

Stdlib ``csv`` on purpose: pandas is not installed in the w124-dash-env.

Usage::

    python3 report.py --collect --manifest ../../models/manifests/gtsdb-yolo26n.yaml
"""
from __future__ import annotations

import argparse
import csv
import json
import pathlib
import shutil

import yaml

HERE = pathlib.Path(__file__).resolve().parent

# Files worth keeping out of a run dir. *.jpg (labels.jpg, train_batch*.jpg) is
# deliberately absent — it is gitignored repo-wide and adds little.
KEEP_GLOBS = ("*.png", "results.csv", "args.yaml", "run_meta.json")


def _metric(metrics: dict, needle: str) -> float | None:
    """Fetch a metric by substring, so a '(B)' suffix change doesn't break us."""
    for key, value in metrics.items():
        if needle in key:
            return float(value)
    return None


def read_lr(results_csv: pathlib.Path) -> tuple[float | None, float | None]:
    """Peak and final ``lr/pg0`` — the lr0 'auto' chose, and where it decayed to.

    Peak, not the first row: epoch 1 sits inside the 3-epoch warmup ramp and
    reads ~0. The schedule climbs to lr0 at the end of warmup and decays from
    there, so the maximum over epochs *is* the resolved lr0.
    """
    if not results_csv.exists():
        return None, None
    with results_csv.open(newline="") as fh:
        rows = [{k.strip(): v for k, v in row.items() if k} for row in csv.DictReader(fh)]
    lrs = [float(r["lr/pg0"]) for r in rows if r.get("lr/pg0") not in (None, "")]
    return (max(lrs), lrs[-1]) if lrs else (None, None)


def collect_run(run_dir: pathlib.Path) -> dict | None:
    """Merge one run's meta, resolved LR and args into a flat record."""
    meta_path = run_dir / "run_meta.json"
    if not meta_path.exists():
        return None
    meta = json.loads(meta_path.read_text())
    lr_peak, lr_last = read_lr(run_dir / "results.csv")
    args_path = run_dir / "args.yaml"
    args = yaml.safe_load(args_path.read_text()) if args_path.exists() else {}
    metrics = meta.get("metrics", {})
    return {
        **meta,
        "lr0_resolved": lr_peak,
        "lr_final": lr_last,
        "optimizer_requested": args.get("optimizer"),
        "fliplr": args.get("fliplr"),
        "map50": _metric(metrics, "mAP50("),
        "map": _metric(metrics, "mAP50-95("),
        "precision": _metric(metrics, "precision("),
        "recall": _metric(metrics, "recall("),
    }


def _fmt(value, spec: str = ".4f") -> str:
    return "—" if value is None else format(value, spec)


def write_comparison(runs: list[dict], out_md: pathlib.Path) -> None:
    out_md.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# GTSDB / YOLO26n — run comparison",
        "",
        "Generated by `report.py`. Metrics come from validating each run's",
        "`weights/best.pt`, not the last epoch in `results.csv`.",
        "",
        "| run | imgsz | classes | epochs | mAP50 | mAP50-95 | precision | recall "
        "| optimizer | lr0 (peak) | lr final | wall |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(runs, key=lambda r: (r.get("label_set", ""), r.get("imgsz", 0))):
        wall = r.get("wall_seconds")
        lines.append(
            f"| `{r.get('run', '?')}` | {r.get('imgsz', '—')} | {len(r.get('names', [])) or '—'} "
            f"| {r.get('epochs_run', '—')}/{r.get('epochs_requested', '—')} "
            f"| {_fmt(r.get('map50'))} | {_fmt(r.get('map'))} "
            f"| {_fmt(r.get('precision'))} | {_fmt(r.get('recall'))} "
            f"| {r.get('optimizer', '—')} | {_fmt(r.get('lr0_resolved'), '.6f')} "
            f"| {_fmt(r.get('lr_final'), '.8f')} "
            f"| {'—' if wall is None else f'{wall / 60:.1f} min'} |"
        )
    lines += [
        "",
        "## Reading these numbers",
        "",
        "- **Cross-label-set comparison is confounded.** `optimizer=\"auto\"` derives",
        "  `lr0 = 0.002 * 5 / (4 + nc)`, so the 4-class and 1-class runs train at",
        "  different learning rates (see the `lr0 (peak)` column). The",
        "  640-vs-1024 comparison *within* a label set is controlled — same `nc`,",
        "  same LR, fixed `seed=0`.",
        "- **`val` doubles as the test set.** We use the official IJCNN 2013 600/300",
        "  split so mAP is comparable to published GTSDB results, but early stopping",
        "  watches the same split it reports on, so these are mildly optimistic.",
        "- **`fliplr=0.0`.** Horizontal flip is disabled: a mirrored \"turn right\"",
        "  *is* \"turn left\", so ultralytics' 0.5 default would corrupt the",
        "  `mandatory` class.",
        "- **These are German signs.** A baseline to prove the pipeline, not a model",
        "  for Thai roads.",
        "",
    ]
    out_md.write_text("\n".join(lines))
    print(f"wrote {out_md}")


def collect_artifacts(runs: list[dict], results_dir: pathlib.Path) -> None:
    """Copy the keepable artifacts out of each run dir into ``results/<run>/``."""
    for r in runs:
        src, dest = pathlib.Path(r["save_dir"]), results_dir / r["run"]
        (dest / "weights").mkdir(parents=True, exist_ok=True)
        for pattern in KEEP_GLOBS:
            for path in src.glob(pattern):
                shutil.copy2(path, dest / path.name)
        for sub in (src / "val_best").glob("*.png"):        # best-checkpoint plots
            shutil.copy2(sub, dest / f"val_{sub.name}")
        best = pathlib.Path(r["best_pt"])
        if best.exists():
            shutil.copy2(best, dest / "weights" / "best.pt")
        for tag, ncnn in r.get("ncnn", {}).items():
            ncnn_path = pathlib.Path(ncnn)
            if ncnn_path.exists():
                shutil.copytree(
                    ncnn_path, dest / "weights" / ncnn_path.name, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns("__pycache__"),   # generated, don't commit
                )
        print(f"collected {r['run']} -> {dest}")


def write_manifest(runs: list[dict], path: pathlib.Path) -> None:
    """Weight metadata only — the .pt files themselves live in Git LFS."""
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Model-weight manifest — metadata only, generated by",
        "# experiments/traffic-sign_recognition/report.py.",
        "#",
        "# The weights are tracked in Git LFS under",
        "# experiments/traffic-sign_recognition/results/<run>/weights/best.pt.",
        "# Verify a copy:  shasum -a 256 best.pt",
        "",
        "base_model: yolo26n            # see models/manifests/yolo26n.yaml",
        "framework: ultralytics-yolo",
        "task: object-detection",
        "dataset: GTSDB (German Traffic Sign Detection Benchmark)",
        "split: official IJCNN 2013 — images 00000-00599 train, 00600-00899 val",
        "",
        "runs:",
    ]
    for r in sorted(runs, key=lambda r: (r.get("label_set", ""), r.get("imgsz", 0))):
        lines += [
            f"  - run: {r['run']}",
            f"    label_set: {r['label_set']}",
            f"    names: [{', '.join(r.get('names', []))}]",
            f"    imgsz: {r['imgsz']}",
            f"    epochs_run: {r.get('epochs_run')}",
            f"    optimizer: {r.get('optimizer')}",
            f"    lr0_resolved: {r.get('lr0_resolved')}",
            f"    map50: {_fmt(r.get('map50'))}",
            f"    map50_95: {_fmt(r.get('map'))}",
            f"    file: results/{r['run']}/weights/best.pt",
            f"    sha256: {r.get('best_pt_sha256')}",
            f"    size_bytes: {r.get('best_pt_bytes')}",
            f"    ncnn: [{', '.join(sorted(r.get('ncnn', {})))}]",
        ]
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--project", type=pathlib.Path, default=HERE / "runs" / "detect",
                        help="dir holding the per-run output directories")
    parser.add_argument("--results", type=pathlib.Path, default=HERE / "results")
    parser.add_argument("--collect", action="store_true",
                        help="copy curated artifacts into --results/<run>/")
    parser.add_argument("--manifest", type=pathlib.Path, default=None,
                        help="also write a weight manifest here")
    args = parser.parse_args(argv)

    runs = [r for d in sorted(args.project.iterdir()) if d.is_dir()
            for r in [collect_run(d)] if r]
    if not runs:
        print(f"no runs with run_meta.json under {args.project}")
        return 1

    write_comparison(runs, args.results / "comparison.md")
    if args.collect:
        collect_artifacts(runs, args.results)
    if args.manifest:
        write_manifest(runs, args.manifest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
